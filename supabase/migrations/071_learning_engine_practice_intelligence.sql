-- ============================================================
-- 7. START LEARNING SESSION
-- ============================================================

create or replace function
public.dmh_academy_start_learning_session(
  p_mission integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_profile public.profiles%rowtype;
  v_enrollment public.academy_enrollments%rowtype;
  v_session public.academy_learning_sessions%rowtype;
  v_now timestamptz :=
    clock_timestamp();
begin

  if p_mission < 1
     or p_mission > 5
  then
    raise exception
      'Learning sessions apply to Missions 1 through 5.';
  end if;


  select p.*
  into v_profile
  from public.profiles p
  where p.id = auth.uid()
    and p.is_active = true
    and p.role::text in (
      'academy',
      'employee'
    );

  if not found then
    raise exception
      'Academy identity required.';
  end if;


  select e.*
  into v_enrollment
  from public.academy_enrollments e
  where e.employee_id =
    auth.uid();

  if not found then
    raise exception
      'Academy enrollment not found.';
  end if;


  if v_profile.role::text = 'academy'
     and v_enrollment.learning_deadline_at
       is not null
     and v_now >
       v_enrollment.learning_deadline_at
  then

    raise exception
      'Academy learning window has expired. Owner extension is required.';

  end if;


  update public.academy_learning_sessions
  set
    status = 'abandoned',
    ended_at = v_now,

    exit_reason =
      coalesce(
        exit_reason,
        'new_session_started'
      ),

    updated_at = v_now

  where employee_id =
      auth.uid()
    and status = 'active';


  insert into public.academy_learning_sessions(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    status,
    started_at,
    last_heartbeat_at
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,
    'active',
    v_now,
    v_now
  )
  returning *
  into v_session;


  insert into public.academy_learning_activity(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    first_opened_at,
    last_activity_at,
    view_count,
    created_at,
    updated_at
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,
    v_now,
    v_now,
    1,
    v_now,
    v_now
  )

  on conflict(
    employee_id,
    academy_version,
    mission_number
  )

  do update
  set
    first_opened_at =
      coalesce(
        public.academy_learning_activity.first_opened_at,
        excluded.first_opened_at
      ),

    last_activity_at =
      excluded.last_activity_at,

    view_count =
      public.academy_learning_activity.view_count + 1,

    updated_at =
      excluded.updated_at;


  return jsonb_build_object(
    'sessionId',
    v_session.id,

    'missionNumber',
    v_session.mission_number,

    'startedAt',
    v_session.started_at,

    'status',
    v_session.status
  );

end;
$function$;


-- ============================================================
-- 8. LEARNING HEARTBEAT
-- ============================================================

create or replace function
public.dmh_academy_learning_heartbeat(
  p_session_id uuid,
  p_visible boolean,
  p_active boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_session public.academy_learning_sessions%rowtype;

  v_now timestamptz :=
    clock_timestamp();

  v_delta integer := 0;

  v_active_add integer := 0;

  v_idle_add integer := 0;

  v_hidden_add integer := 0;
begin

  select s.*
  into v_session
  from public.academy_learning_sessions s
  where s.id =
      p_session_id
    and s.employee_id =
      auth.uid()
  for update;


  if not found then
    raise exception
      'Learning session not found.';
  end if;


  if v_session.status <> 'active' then

    return jsonb_build_object(
      'sessionId',
      v_session.id,

      'status',
      v_session.status,

      'activeSeconds',
      v_session.active_seconds,

      'idleSeconds',
      v_session.idle_seconds,

      'hiddenSeconds',
      v_session.hidden_seconds
    );

  end if;


  v_delta :=
    least(
      60,

      greatest(
        0,

        floor(
          extract(
            epoch from (
              v_now
              - v_session.last_heartbeat_at
            )
          )
        )::integer
      )
    );


  if not coalesce(
    p_visible,
    false
  )
  then

    v_hidden_add :=
      v_delta;

  elsif coalesce(
    p_active,
    false
  )
  then

    v_active_add :=
      v_delta;

  else

    v_idle_add :=
      v_delta;

  end if;


  update public.academy_learning_sessions
  set
    active_seconds =
      active_seconds +
      v_active_add,

    idle_seconds =
      idle_seconds +
      v_idle_add,

    hidden_seconds =
      hidden_seconds +
      v_hidden_add,

    heartbeat_count =
      heartbeat_count + 1,

    last_heartbeat_at =
      v_now,

    updated_at =
      v_now

  where id =
    p_session_id

  returning *
  into v_session;


  if v_active_add > 0 then

    update public.academy_learning_activity
    set
      active_seconds =
        active_seconds +
        v_active_add,

      last_activity_at =
        v_now,

      updated_at =
        v_now

    where employee_id =
        auth.uid()

      and academy_version =
        v_session.academy_version

      and mission_number =
        v_session.mission_number;

  end if;


  return jsonb_build_object(
    'sessionId',
    v_session.id,

    'status',
    v_session.status,

    'activeSeconds',
    v_session.active_seconds,

    'idleSeconds',
    v_session.idle_seconds,

    'hiddenSeconds',
    v_session.hidden_seconds
  );

end;
$function$;


