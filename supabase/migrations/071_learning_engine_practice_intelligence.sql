create or replace function
public.dmh_academy_record_learning_activity(
  p_mission integer,
  p_event text,
  p_score numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_profile public.profiles%rowtype;

  v_enrollment public.academy_enrollments%rowtype;

  v_activity public.academy_learning_activity%rowtype;

  v_increment integer := 0;

  v_now timestamptz :=
    clock_timestamp();
begin

  if p_mission < 1
     or p_mission > 5
  then
    raise exception
      'Learning analytics apply to Missions 1 through 5.';
  end if;


  if p_event not in (
    'open',
    'heartbeat',
    'practice',
    'complete'
  ) then
    raise exception
      'Unsupported Academy learning event.';
  end if;


  if p_score is not null
     and (
       p_score < 0
       or p_score > 100
     )
  then
    raise exception
      'Practice score must be between 0 and 100.';
  end if;


  select p.*
  into v_profile
  from public.profiles p
  where p.id = auth.uid()
    and p.role::text in (
      'academy',
      'employee'
    )
    and p.is_active = true;

  if not found then
    raise exception
      'Academy access required.';
  end if;


  select e.*
  into v_enrollment
  from public.academy_enrollments e
  where e.employee_id =
    auth.uid()
  for update;

  if not found then
    raise exception
      'Academy enrollment not found.';
  end if;


  if v_profile.role::text = 'academy'
     and v_now >
       v_enrollment.learning_deadline_at
  then

    raise exception
      'Academy learning window has expired. Owner extension is required.';

  end if;


  insert into public.academy_learning_activity(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    first_opened_at,
    last_activity_at,
    view_count
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,
    v_now,
    v_now,
    case
      when p_event = 'open'
        then 1
      else 0
    end
  )
  on conflict (
    employee_id,
    academy_version,
    mission_number
  )
  do nothing;


  select a.*
  into v_activity
  from public.academy_learning_activity a
  where a.employee_id =
      auth.uid()
    and a.academy_version =
      v_enrollment.academy_version
    and a.mission_number =
      p_mission
  for update;


  if p_event = 'heartbeat'
     and v_activity.last_activity_at
       is not null
  then

    v_increment :=
      least(
        60,
        greatest(
          0,
          floor(
            extract(
              epoch from (
                v_now
                - v_activity.last_activity_at
              )
            )
          )::integer
        )
      );

  end if;


  update public.academy_learning_activity
  set

    first_opened_at =
      coalesce(
        first_opened_at,
        v_now
      ),

    last_activity_at =
      v_now,

    active_seconds =
      active_seconds
      +
      case
        when p_event = 'heartbeat'
          then v_increment
        else 0
      end,

    view_count =
      view_count
      +
      case
        when p_event = 'open'
          then 1
        else 0
      end,

    practice_attempt_count =
      practice_attempt_count
      +
      case
        when p_event = 'practice'
          then 1
        else 0
      end,

    first_practice_score =
      case
        when p_event = 'practice'
             and first_practice_score
               is null
        then p_score
        else first_practice_score
      end,

    best_practice_score =
      case
        when p_event = 'practice'
        then greatest(
          coalesce(
            best_practice_score,
            0
          ),
          coalesce(
            p_score,
            0
          )
        )
        else best_practice_score
      end,

    latest_practice_score =
      case
        when p_event = 'practice'
          then p_score
        else latest_practice_score
      end,

    completed_at =
      case
        when p_event = 'complete'
        then coalesce(
          completed_at,
          v_now
        )
        else completed_at
      end,

    updated_at =
      v_now

  where employee_id =
      auth.uid()
    and academy_version =
      v_enrollment.academy_version
    and mission_number =
      p_mission;


  insert into public.academy_learning_events(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    event_type,
    metadata
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,

    case p_event
      when 'open'
        then 'mission_opened'
      when 'heartbeat'
        then 'heartbeat'
      when 'practice'
        then 'practice_submitted'
      else 'mission_completed'
    end,

    jsonb_build_object(
      'score',
      p_score,
      'active_seconds_added',
      v_increment
    )
  );


  if p_event = 'complete' then

    if (
      select count(*)
      from public.academy_learning_activity a
      where a.employee_id =
          auth.uid()
        and a.academy_version =
          v_enrollment.academy_version
        and a.completed_at
          is not null
    ) >= 5
    then

      update public.academy_enrollments
      set
        learning_completed_at =
          coalesce(
            learning_completed_at,
            v_now
          ),
        updated_at = now()
      where employee_id =
        auth.uid();

    end if;

  end if;


  return public.dmh_academy_learning_state();

end;
$function$;


-- ============================================================
-- 12. RECORD EVERY PRACTICE ATTEMPT
-- ============================================================

create or replace function
public.dmh_academy_record_practice_attempt(
  p_mission integer,
  p_score numeric,
  p_question_count integer,
  p_correct_count integer,
  p_passed boolean,
  p_started_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_profile public.profiles%rowtype;

  v_enrollment public.academy_enrollments%rowtype;

  v_attempt integer;

  v_now timestamptz :=
    clock_timestamp();

  v_duration integer;

  v_first_score numeric;

  v_best_score numeric;

  v_attempt_count bigint;
begin

  if p_mission < 1
     or p_mission > 5
  then
    raise exception
      'Practice attempts apply to Missions 1 through 5.';
  end if;


  if p_score < 0
     or p_score > 100
  then
    raise exception
      'Practice score must be between 0 and 100.';
  end if;


  if p_question_count <= 0 then
    raise exception
      'Question count must be greater than zero.';
  end if;


  if p_correct_count < 0
     or p_correct_count >
       p_question_count
  then
    raise exception
      'Correct count is invalid.';
  end if;


  select p.*
  into v_profile
  from public.profiles p
  where p.id =
      auth.uid()
    and p.is_active =
      true
    and p.role::text in (
      'academy',
      'employee'
    );

  if not found then
    raise exception
      'Academy identity required.';
  end if;


  select e.*
  into v_enrollment
  from public.academy_enrollments e
  where e.employee_id =
    auth.uid();

  if not found then
    raise exception
      'Academy enrollment not found.';
  end if;


  select
    coalesce(
      max(a.attempt_number),
      0
    ) + 1
  into v_attempt
  from public.academy_practice_attempts a
  where a.employee_id =
      auth.uid()

    and a.academy_version =
      v_enrollment.academy_version

    and a.mission_number =
      p_mission;


  v_duration :=
    case

      when p_started_at is null
      then null

      else greatest(
        0,

        floor(
          extract(
            epoch from (
              v_now -
              p_started_at
            )
          )
        )::integer
      )

    end;


  insert into public.academy_practice_attempts(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    attempt_number,
    score,
    question_count,
    correct_count,
    passed,
    started_at,
    submitted_at,
    duration_seconds,
    verification_level
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,
    v_attempt,
    p_score,
    p_question_count,
    p_correct_count,
    p_passed,
    p_started_at,
    v_now,
    v_duration,
    'client_reported'
  );


  insert into public.academy_learning_activity(
    employee_id,
    company_id,
    academy_version,
    mission_number,
    first_opened_at,
    last_activity_at,
    practice_attempt_count,
    first_practice_score,
    best_practice_score,
    latest_practice_score,
    created_at,
    updated_at
  )
  values(
    auth.uid(),
    v_profile.company_id,
    v_enrollment.academy_version,
    p_mission,
    v_now,
    v_now,
    1,
    p_score,
    p_score,
    p_score,
    v_now,
    v_now
  )

  on conflict(
    employee_id,
    academy_version,
    mission_number
  )

  do update
  set
    last_activity_at =
      excluded.last_activity_at,

    practice_attempt_count =
      public.academy_learning_activity.practice_attempt_count + 1,

    first_practice_score =
      coalesce(
        public.academy_learning_activity.first_practice_score,
        excluded.first_practice_score
      ),

    best_practice_score =
      greatest(
        coalesce(
          public.academy_learning_activity.best_practice_score,
          0
        ),
        excluded.best_practice_score
      ),

    latest_practice_score =
      excluded.latest_practice_score,

    updated_at =
      excluded.updated_at;


  select
    min(a.score)
      filter (
        where a.attempt_number = 1
      ),

    max(a.score),

    count(*)

  into
    v_first_score,
    v_best_score,
    v_attempt_count

  from public.academy_practice_attempts a

  where a.employee_id =
      auth.uid()

    and a.academy_version =
      v_enrollment.academy_version

    and a.mission_number =
      p_mission;


  return jsonb_build_object(
    'missionNumber',
    p_mission,

    'attemptNumber',
    v_attempt,

    'score',
    p_score,

    'passed',
    p_passed,

    'firstAttemptScore',
    v_first_score,

    'bestScore',
    v_best_score,

    'attemptCount',
    v_attempt_count
  );

end;
$function$;


-- ============================================================
-- 13. OWNER LEARNING ENGINE DOSSIER
-- ============================================================

create or replace function
public.dmh_owner_learning_engine_summary(
  p_employee_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_profile public.profiles%rowtype;

  v_sessions jsonb;

  v_missions jsonb;

  v_attempts jsonb;

  v_totals jsonb;
begin

  if public.current_role()::text <>
    'owner'
  then
    raise exception
      'Owner access required.';
  end if;


  select p.*
  into v_profile
  from public.profiles p
  where p.id =
      p_employee_id

    and p.company_id =
      public.current_company_id();


  if not found then
    raise exception
      'Candidate or employee not found.';
  end if;


  select jsonb_build_object(

    'sessionCount',
    count(*),

    'activeSeconds',
    coalesce(
      sum(s.active_seconds),
      0
    ),

    'idleSeconds',
    coalesce(
      sum(s.idle_seconds),
      0
    ),

    'hiddenSeconds',
    coalesce(
      sum(s.hidden_seconds),
      0
    ),

    'firstSessionAt',
    min(s.started_at),

    'lastSessionAt',
    max(
      coalesce(
        s.ended_at,
        s.last_heartbeat_at
      )
    )

  )
  into v_totals

  from public.academy_learning_sessions s

  where s.employee_id =
    p_employee_id;


  select coalesce(
    jsonb_agg(
      jsonb_build_object(

        'missionNumber',
        x.mission_number,

        'sessionCount',
        x.session_count,

        'activeSeconds',
        x.active_seconds,

        'idleSeconds',
        x.idle_seconds,

        'hiddenSeconds',
        x.hidden_seconds,

        'firstOpenedAt',
        x.first_opened_at,

        'lastActivityAt',
        x.last_activity_at

      )
      order by
        x.mission_number
    ),

    '[]'::jsonb
  )
  into v_missions

  from (

    select
      s.mission_number,

      count(*)
        as session_count,

      coalesce(
        sum(s.active_seconds),
        0
      )
        as active_seconds,

      coalesce(
        sum(s.idle_seconds),
        0
      )
        as idle_seconds,

      coalesce(
        sum(s.hidden_seconds),
        0
      )
        as hidden_seconds,

      min(s.started_at)
        as first_opened_at,

      max(
        coalesce(
          s.ended_at,
          s.last_heartbeat_at
        )
      )
        as last_activity_at

    from public.academy_learning_sessions s

    where s.employee_id =
      p_employee_id

    group by
      s.mission_number

  ) x;


  select coalesce(
    jsonb_agg(
      jsonb_build_object(

        'id',
        a.id,

        'missionNumber',
        a.mission_number,

        'attemptNumber',
        a.attempt_number,

        'score',
        a.score,

        'passed',
        a.passed,

        'questionCount',
        a.question_count,

        'correctCount',
        a.correct_count,

        'durationSeconds',
        a.duration_seconds,

        'verificationLevel',
        a.verification_level,

        'submittedAt',
        a.submitted_at

      )

      order by
        a.mission_number,
        a.attempt_number
    ),

    '[]'::jsonb
  )
  into v_attempts

  from public.academy_practice_attempts a

  where a.employee_id =
    p_employee_id;


  select coalesce(
    jsonb_agg(
      jsonb_build_object(

        'id',
        s.id,

        'missionNumber',
        s.mission_number,

        'status',
        s.status,

        'startedAt',
        s.started_at,

        'endedAt',
        s.ended_at,

        'activeSeconds',
        s.active_seconds,

        'idleSeconds',
        s.idle_seconds,

        'hiddenSeconds',
        s.hidden_seconds,

        'heartbeatCount',
        s.heartbeat_count,

        'exitReason',
        s.exit_reason

      )

      order by
        s.started_at desc
    ),

    '[]'::jsonb
  )
  into v_sessions

  from public.academy_learning_sessions s

  where s.employee_id =
    p_employee_id;


  return jsonb_build_object(
    'employeeId',
    p_employee_id,

    'totals',
    coalesce(
      v_totals,
      '{}'::jsonb
    ),

    'missions',
    coalesce(
      v_missions,
      '[]'::jsonb
    ),

    'practiceAttempts',
    coalesce(
      v_attempts,
      '[]'::jsonb
    ),

    'sessions',
    coalesce(
      v_sessions,
      '[]'::jsonb
    )
  );

end;
$function$;


