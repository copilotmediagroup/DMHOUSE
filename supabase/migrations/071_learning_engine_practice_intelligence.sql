-- ============================================================
-- 10. LEARNING STATE
-- ============================================================

create or replace function
public.dmh_academy_learning_state()
returns jsonb
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_profile public.profiles%rowtype;

  v_enrollment public.academy_enrollments%rowtype;

  v_total_active integer;

  v_completed integer;

  v_average_score numeric;

  v_elapsed interval;

  v_pace text;

  v_remaining_seconds bigint;

  v_next_attempt_seconds bigint;
begin

  select p.*
  into v_profile
  from public.profiles p
  where p.id = auth.uid()
    and p.is_active = true;

  if not found then
    raise exception
      'Active DMHOUSE profile required.';
  end if;


  select e.*
  into v_enrollment
  from public.academy_enrollments e
  where e.employee_id =
    auth.uid();

  if not found then
    raise exception
      'Academy enrollment not found.';
  end if;


  select
    coalesce(
      sum(a.active_seconds),
      0
    ),

    count(*) filter (
      where a.completed_at
        is not null
    ),

    round(
      avg(
        a.best_practice_score
      ),
      2
    )

  into
    v_total_active,
    v_completed,
    v_average_score

  from public.academy_learning_activity a
  where a.employee_id =
    auth.uid()
    and a.academy_version =
      v_enrollment.academy_version;


  v_elapsed :=
    now()
    -
    v_enrollment.learning_started_at;


  if v_enrollment.learning_completed_at
       is not null
  then

    v_pace := 'completed';

  elsif now() >
        v_enrollment.learning_deadline_at
  then

    v_pace := 'expired';

  elsif now() >
        v_enrollment.learning_target_at
  then

    v_pace := 'late';

  elsif now() >
        v_enrollment.learning_started_at
        + interval '24 hours'
  then

    v_pace := 'on_track';

  else

    v_pace := 'excellent';

  end if;


  v_remaining_seconds :=
    greatest(
      0,
      floor(
        extract(
          epoch from (
            v_enrollment.learning_deadline_at
            - now()
          )
        )
      )::bigint
    );


  v_next_attempt_seconds :=
    case

      when v_enrollment.next_final_attempt_at
           is null
      then 0

      else greatest(
        0,
        floor(
          extract(
            epoch from (
              v_enrollment.next_final_attempt_at
              - now()
            )
          )
        )::bigint
      )

    end;


  return jsonb_build_object(

    'learningStartedAt',
    v_enrollment.learning_started_at,

    'learningTargetAt',
    v_enrollment.learning_target_at,

    'learningDeadlineAt',
    v_enrollment.learning_deadline_at,

    'learningCompletedAt',
    v_enrollment.learning_completed_at,

    'learningPace',
    v_pace,

    'secondsUntilExpiration',
    v_remaining_seconds,

    'missionsCompleted',
    v_completed,

    'missionsRequired',
    5,

    'activeLearningSeconds',
    v_total_active,

    'averagePracticeScore',
    v_average_score,

    'finalAttemptsUsed',
    v_enrollment.final_attempts_used,

    'finalAttemptLimit',
    v_enrollment.final_attempt_limit,

    'nextFinalAttemptAt',
    v_enrollment.next_final_attempt_at,

    'secondsUntilNextAttempt',
    v_next_attempt_seconds,

    'finalAssessmentStatus',
    v_enrollment.final_assessment_status
  );

end;
$function$;


