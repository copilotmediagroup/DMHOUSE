create or replace function
public.dmh_owner_reinstate_employee(
  p_employee_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_employee public.profiles%rowtype;

  v_current text;

  v_reason text :=
    nullif(
      btrim(
        coalesce(
          p_reason,
          ''
        )
      ),
      ''
    );

  v_now timestamptz :=
    clock_timestamp();
begin

  v_employee :=
    public.dmh_assert_owner_employee(
      p_employee_id
    );


  select status
  into v_current
  from public.employee_employment_state
  where employee_id =
    p_employee_id
  for update;


  if v_current = 'terminated' then
    raise exception
      'Terminated employee requires Rehire.';
  end if;


  if v_current <> 'suspended' then
    raise exception
      'Only suspended employees can be reinstated.';
  end if;


  update public.employee_employment_state
  set
    status =
      'active',

    rehired_at =
      null,

    rehired_by =
      null,

    rehire_reason =
      null

  where employee_id =
    p_employee_id;


  update public.profiles
  set is_active = true
  where id =
    p_employee_id;


  insert into
  public.employee_employment_events(
    employee_id,
    company_id,
    actor_id,
    event_type,
    reason,
    metadata
  )
  values(
    p_employee_id,
    v_employee.company_id,
    auth.uid(),

    'employee.reinstated',

    coalesce(
      v_reason,
      'Suspension lifted by Owner.'
    ),

    jsonb_build_object(
      'previousStatus',
      'suspended',

      'newStatus',
      'active'
    )
  );


  return jsonb_build_object(
    'employeeId',
    p_employee_id,

    'status',
    'active',

    'isActive',
    true,

    'reinstatedAt',
    v_now
  );

end;
$function$;


-- ============================================================
-- 9. TERMINATE EMPLOYEE
-- ============================================================

create or replace function
public.dmh_owner_terminate_employee(
  p_employee_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_employee public.profiles%rowtype;

  v_current text;

  v_reason text :=
    nullif(
      btrim(
        coalesce(
          p_reason,
          ''
        )
      ),
      ''
    );

  v_now timestamptz :=
    clock_timestamp();

  v_candidate_id uuid;

  v_cycle_id uuid;
begin

  v_employee :=
    public.dmh_assert_owner_employee(
      p_employee_id
    );


  if v_reason is null
     or length(v_reason) < 5
  then

    raise exception
      'A meaningful termination reason is required.';

  end if;


  select status
  into v_current
  from public.employee_employment_state
  where employee_id =
    p_employee_id
  for update;


  if v_current = 'terminated' then
    raise exception
      'Employee is already terminated.';
  end if;


  update public.employee_employment_state
  set
    status =
      'terminated',

    terminated_at =
      v_now,

    terminated_by =
      auth.uid(),

    termination_reason =
      v_reason

  where employee_id =
    p_employee_id;


  -- Sales OS access is revoked.

  update public.profiles
  set is_active = false
  where id =
    p_employee_id;


  insert into
  public.employee_employment_events(
    employee_id,
    company_id,
    actor_id,
    event_type,
    reason,
    metadata
  )
  values(
    p_employee_id,
    v_employee.company_id,
    auth.uid(),

    'employee.terminated',

    v_reason,

    jsonb_build_object(
      'previousStatus',
      v_current,

      'newStatus',
      'terminated',

      'salesOsAccess',
      'revoked'
    )
  );


  -- Mirror important termination event
  -- into Hiring OS history when the employee
  -- originated through Academy.

  select c.id
  into v_candidate_id
  from public.hiring_candidates c
  where c.user_id =
    p_employee_id;


  if v_candidate_id is not null then

    select cy.id
    into v_cycle_id
    from public.hiring_candidate_cycles cy
    where cy.candidate_id =
      v_candidate_id
    order by
      cy.created_at desc
    limit 1;


    insert into public.hiring_events(
      candidate_id,
      cycle_id,
      company_id,
      actor_id,
      event_type,
      source_type,
      source_key,
      metadata,
      created_at
    )
    values(
      v_candidate_id,

      v_cycle_id,

      v_employee.company_id,

      auth.uid(),

      'employee.terminated',

      'employee_employment_events',

      p_employee_id::text
      ||
      ':terminated:'
      ||
      extract(
        epoch from v_now
      )::bigint::text,

      jsonb_build_object(
        'reason',
        v_reason,

        'salesOsAccess',
        'revoked'
      ),

      v_now
    );

  end if;


  return jsonb_build_object(
    'employeeId',
    p_employee_id,

    'status',
    'terminated',

    'isActive',
    false,

    'terminatedAt',
    v_now
  );

end;
$function$;


