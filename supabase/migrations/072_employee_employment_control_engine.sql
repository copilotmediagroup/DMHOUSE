-- ============================================================
-- 1. CANONICAL EMPLOYMENT STATE
-- ============================================================

create table if not exists
public.employee_employment_state (

  employee_id uuid primary key
    references public.profiles(id)
    on delete cascade,

  company_id uuid not null
    references public.companies(id)
    on delete cascade,

  status text not null
    default 'active'
    check (
      status in (
        'active',
        'suspended',
        'terminated'
      )
    ),

  suspended_at timestamptz,

  suspended_by uuid,

  suspension_reason text,

  terminated_at timestamptz,

  terminated_by uuid,

  termination_reason text,

  rehired_at timestamptz,

  rehired_by uuid,

  rehire_reason text,

  created_at timestamptz not null
    default now(),

  updated_at timestamptz not null
    default now()
);


create index if not exists
employee_employment_state_company_idx
on public.employee_employment_state(
  company_id,
  status
);


-- ============================================================
-- 2. IMMUTABLE EMPLOYMENT EVENT HISTORY
-- ============================================================

create table if not exists
public.employee_employment_events (

  id bigint generated by default
    as identity
    primary key,

  employee_id uuid not null
    references public.profiles(id)
    on delete cascade,

  company_id uuid not null
    references public.companies(id)
    on delete cascade,

  actor_id uuid,

  event_type text not null
    check (
      event_type in (
        'employee.employment_created',
        'employee.suspended',
        'employee.reinstated',
        'employee.terminated',
        'employee.rehired'
      )
    ),

  reason text,

  metadata jsonb not null
    default '{}'::jsonb,

  created_at timestamptz not null
    default now()
);


create index if not exists
employee_employment_events_company_idx
on public.employee_employment_events(
  company_id,
  created_at desc
);


create index if not exists
employee_employment_events_employee_idx
on public.employee_employment_events(
  employee_id,
  created_at desc
);


