-- 10. REHIRE TERMINATED EMPLOYEE
-- ============================================================

create or replace function
public.dmh_owner_rehire_employee(
  p_employee_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_employee public.profiles%rowtype;

  v_current text;

  v_reason text :=
    nullif(
      btrim(
        coalesce(
          p_reason,
          ''
        )
      ),
      ''
    );

  v_now timestamptz :=
    clock_timestamp();
begin

  v_employee :=
    public.dmh_assert_owner_employee(
      p_employee_id
    );


  if v_reason is null then
    raise exception
      'Rehire reason is required.';
  end if;


  select status
  into v_current
  from public.employee_employment_state
  where employee_id =
    p_employee_id
  for update;


  if v_current <> 'terminated' then
    raise exception
      'Only terminated employees use the Rehire action.';
  end if;


  -- IMPORTANT:
  -- Employment state changes FIRST.
  --
  -- Migration 073's profile protection
  -- permits profile activation only after
  -- employment status is no longer terminated.

  update public.employee_employment_state
  set
    status =
      'active',

    rehired_at =
      v_now,

    rehired_by =
      auth.uid(),

    rehire_reason =
      v_reason

  where employee_id =
    p_employee_id;


  update public.profiles
  set is_active = true
  where id =
    p_employee_id;


  insert into
  public.employee_employment_events(
    employee_id,
    company_id,
    actor_id,
    event_type,
    reason,
    metadata
  )
  values(
    p_employee_id,

    v_employee.company_id,

    auth.uid(),

    'employee.rehired',

    v_reason,

    jsonb_build_object(
      'previousStatus',
      'terminated',

      'newStatus',
      'active'
    )
  );


  return jsonb_build_object(
    'employeeId',
    p_employee_id,

    'status',
    'active',

    'isActive',
    true,

    'rehiredAt',
    v_now
  );

end;
$function$;


