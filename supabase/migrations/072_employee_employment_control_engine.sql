-- ============================================================
-- 5. OWNER → EMPLOYEE AUTHORIZATION GATE
-- ============================================================

create or replace function
public.dmh_assert_owner_employee(
  p_employee_id uuid
)
returns public.profiles
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_employee public.profiles%rowtype;
begin

  if public.current_role()::text <> 'owner' then
    raise exception
      'Owner access required.';
  end if;


  select p.*
  into v_employee
  from public.profiles p
  where p.id =
      p_employee_id

    and p.company_id =
      public.current_company_id()

    and p.role::text =
      'employee';


  if not found then
    raise exception
      'Employee not found.';
  end if;


  return v_employee;

end;
$function$;


-- ============================================================
-- 6. OWNER EMPLOYMENT ROSTER
-- ============================================================

create or replace function
public.dmh_owner_employment_roster()
returns table(
  employee_id uuid,
  employment_status text,
  suspended_at timestamptz,
  suspension_reason text,
  terminated_at timestamptz,
  termination_reason text,
  rehired_at timestamptz,
  rehire_reason text,
  updated_at timestamptz
)
language sql
security definer
set search_path to 'public'
as $function$

  select
    s.employee_id,

    s.status
      as employment_status,

    s.suspended_at,

    s.suspension_reason,

    s.terminated_at,

    s.termination_reason,

    s.rehired_at,

    s.rehire_reason,

    s.updated_at

  from public.employee_employment_state s

  where
    public.current_role()::text =
      'owner'

    and

    s.company_id =
      public.current_company_id()

  order by
    s.updated_at desc;

$function$;


-- ============================================================
-- 7. SUSPEND EMPLOYEE
-- ============================================================

create or replace function
public.dmh_owner_suspend_employee(
  p_employee_id uuid,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_employee public.profiles%rowtype;

  v_reason text :=
    nullif(
      btrim(
        coalesce(
          p_reason,
          ''
        )
      ),
      ''
    );

  v_current text;

  v_now timestamptz :=
    clock_timestamp();
begin

  v_employee :=
    public.dmh_assert_owner_employee(
      p_employee_id
    );


  if v_reason is null then
    raise exception
      'Suspension reason is required.';
  end if;


  select status
  into v_current
  from public.employee_employment_state
  where employee_id =
    p_employee_id
  for update;


  if v_current = 'terminated' then
    raise exception
      'Employee is terminated. Use Rehire instead.';
  end if;


  if v_current = 'suspended' then
    raise exception
      'Employee is already suspended.';
  end if;


  update public.employee_employment_state
  set
    status =
      'suspended',

    suspended_at =
      v_now,

    suspended_by =
      auth.uid(),

    suspension_reason =
      v_reason

  where employee_id =
    p_employee_id;


  update public.profiles
  set is_active = false
  where id =
    p_employee_id;


  insert into
  public.employee_employment_events(
    employee_id,
    company_id,
    actor_id,
    event_type,
    reason,
    metadata
  )
  values(
    p_employee_id,
    v_employee.company_id,
    auth.uid(),

    'employee.suspended',

    v_reason,

    jsonb_build_object(
      'previousStatus',
      v_current,

      'newStatus',
      'suspended'
    )
  );


  return jsonb_build_object(
    'employeeId',
    p_employee_id,

    'status',
    'suspended',

    'isActive',
    false,

    'suspendedAt',
    v_now
  );

end;
$function$;


