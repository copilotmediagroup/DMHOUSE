-- ============================================================
-- 9. OWNER TERRITORY COMMAND INTELLIGENCE
--
-- 30-day cooldown is the initial default.
-- It is advisory, not a hard prohibition.
-- ============================================================

create or replace function
public.dmh_owner_territory_intelligence(
  p_cooldown_days integer default 30
)
returns table(

  market_key text,

  territory_name text,

  center_address text,

  center_latitude numeric,

  center_longitude numeric,

  radius_miles numeric,

  assignment_count bigint,

  employee_count bigint,

  current_territory_id uuid,

  current_employee_id uuid,

  current_employee_name text,

  current_status text,

  current_starts_at timestamptz,

  current_expires_at timestamptz,

  last_employee_id uuid,

  last_employee_name text,

  last_started_at timestamptz,

  last_worked_at timestamptz,

  days_since_last_worked integer,

  cooldown_days integer,

  recommended_next_assignment_at timestamptz,

  recommendation text
)
language sql
security definer
set search_path to 'public'
as $function$

with authorized as (

  select
    r.*,

    case

      when r.assignment_status =
        'removed'
      then
        'removed'

      else
        public.dmh_territory_effective_status(
          r.source_status,
          r.starts_at,
          r.expires_at
        )

    end
      as effective_assignment_status

  from public.territory_assignment_registry r

  where
    public.current_role()::text =
      'owner'

    and

    r.company_id =
      public.current_company_id()
),


market_rollup as (

  select
    a.market_key,

    count(*)::bigint
      as assignment_count,

    count(
      distinct a.employee_id
    )::bigint
      as employee_count

  from authorized a

  group by
    a.market_key
),


ranked as (

  select
    a.*,

    row_number() over(
      partition by a.market_key
      order by
        a.starts_at desc,
        a.first_seen_at desc,
        a.territory_id desc
    )
      as rn

  from authorized a
),


latest as (

  select
    r.*,
    m.assignment_count,
    m.employee_count

  from ranked r

  join market_rollup m
    on m.market_key =
      r.market_key

  where r.rn = 1
),


resolved as (

  select
    l.*,

    coalesce(
      l.removed_at,

      l.completed_at,

      case
        when l.expires_at is not null
          and l.expires_at <= now()
        then l.expires_at
        else null
      end,

      l.last_seen_at
    )
      as resolved_last_worked_at

  from latest l
)


select

  l.market_key,

  l.territory_name,

  l.center_address,

  l.center_latitude,

  l.center_longitude,

  l.radius_miles,

  l.assignment_count,

  l.employee_count,


  case
    when l.effective_assignment_status in (
      'active',
      'scheduled'
    )
    then l.territory_id
    else null
  end
    as current_territory_id,


  case
    when l.effective_assignment_status in (
      'active',
      'scheduled'
    )
    then l.employee_id
    else null
  end
    as current_employee_id,


  case
    when l.effective_assignment_status in (
      'active',
      'scheduled'
    )
    then current_employee.full_name
    else null
  end
    as current_employee_name,


  l.effective_assignment_status
    as current_status,


  l.starts_at
    as current_starts_at,


  l.expires_at
    as current_expires_at,


  l.employee_id
    as last_employee_id,


  last_employee.full_name
    as last_employee_name,


  l.starts_at
    as last_started_at,


  l.resolved_last_worked_at
    as last_worked_at,


  case

    when l.effective_assignment_status in (
      'active',
      'scheduled'
    )
    then 0

    else greatest(
      0,

      floor(
        extract(
          epoch from (
            now()
            -
            l.resolved_last_worked_at
          )
        )
        /
        86400
      )::integer
    )

  end
    as days_since_last_worked,


  greatest(
    1,
    coalesce(
      p_cooldown_days,
      30
    )
  )
    as cooldown_days,


  case

    when l.effective_assignment_status in (
      'active',
      'scheduled'
    )
    then null

    else
      l.resolved_last_worked_at
      +
      make_interval(
        days =>
          greatest(
            1,
            coalesce(
              p_cooldown_days,
              30
            )
          )
      )

  end
    as recommended_next_assignment_at,


  case

    when l.effective_assignment_status =
      'active'
    then
      'ACTIVE'

    when l.effective_assignment_status =
      'scheduled'
    then
      'SCHEDULED'

    when
      now()
      >=
      l.resolved_last_worked_at
      +
      make_interval(
        days =>
          greatest(
            1,
            coalesce(
              p_cooldown_days,
              30
            )
          )
      )
    then
      'READY'

    else
      'COOLING'

  end
    as recommendation


from resolved l


left join public.profiles current_employee
  on current_employee.id =
    case

      when l.effective_assignment_status in (
        'active',
        'scheduled'
      )

      then l.employee_id

      else null

    end


left join public.profiles last_employee
  on last_employee.id =
    l.employee_id


order by

  case

    when l.effective_assignment_status =
      'active'
    then 1

    when l.effective_assignment_status =
      'scheduled'
    then 2

    when
      now()
      >=
      l.resolved_last_worked_at
      +
      make_interval(
        days =>
          greatest(
            1,
            coalesce(
              p_cooldown_days,
              30
            )
          )
      )
    then 3

    else 4

  end,

  l.starts_at desc;

$function$;


revoke all
on function
public.dmh_owner_territory_intelligence(integer)
from public;


grant execute
on function
public.dmh_owner_territory_intelligence(integer)
to authenticated;


